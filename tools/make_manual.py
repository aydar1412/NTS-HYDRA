def sheet_mock(fig, rect, title, headers, rows, widths=None, fill_from=1,
                 note=None):
    """Рисует лист исходных данных так, как он выглядит в таблице."""
    ax = fig.add_axes(rect)
    ax.axis("off")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    n = len(headers)
    w = widths or [1.0 / n] * n
    w = [v / sum(w) for v in w]
    x = np.concatenate([[0], np.cumsum(w)])
    rh = 1.0 / (len(rows) + 3.2)

    ax.text(0, 1.0 - rh * 0.4, title, fontsize=9.2, fontweight="bold",
            va="center")
    ax.add_patch(Rectangle((0, 1 - rh * 1.25), 1, rh * 0.14,
                           color=C["yellow"], transform=ax.transAxes))

    ytop = 1 - rh * 1.45
    ax.add_patch(Rectangle((0, ytop - rh), 1, rh, color=C["accent"],
                           transform=ax.transAxes))
    for j, hh in enumerate(headers):
        ax.text(x[j] + w[j] / 2, ytop - rh / 2, hh, ha="center",
                va="center", fontsize=6.3, color="white",
                fontweight="bold", transform=ax.transAxes)

    for i, row in enumerate(rows):
        yy = ytop - rh * (i + 2)
        for j, cell in enumerate(row):
            if j >= fill_from:
                ax.add_patch(Rectangle((x[j], yy), w[j], rh,
                                       facecolor="#FFF8DC",
                                       edgecolor="#E2DFD6", lw=0.4,
                                       transform=ax.transAxes))
            else:
                ax.add_patch(Rectangle((x[j], yy), w[j], rh,
                                       facecolor="white",
                                       edgecolor="#E2DFD6", lw=0.4,
                                       transform=ax.transAxes))
            col = C["bad"] if str(cell).strip().lower() == "н/д" else C["text"]
            ax.text(x[j] + w[j] / 2 if j else x[j] + 0.006,
                    yy + rh / 2, str(cell),
                    ha="center" if j else "left", va="center",
                    fontsize=6.2, color=col,
                    fontweight="bold" if j == 0 else "normal",
                    transform=ax.transAxes)
    if note:
        ax.text(0, ytop - rh * (len(rows) + 2.35), note, fontsize=6.6,
                color="#7A7A7C", style="italic", transform=ax.transAxes)
    return ax


