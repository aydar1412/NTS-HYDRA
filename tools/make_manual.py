def report_pages():
    """Растеризует страницы готового отчёта. Возвращает список массивов."""
    if not os.path.exists(REPORT):
        return []
    try:
        import fitz
    except ImportError:
        try:
            import pymupdf as fitz
        except ImportError:
            return []
    doc = fitz.open(REPORT)
    out = []
    for pg in doc:
        pm = pg.get_pixmap(dpi=150)
        arr = np.frombuffer(pm.samples, dtype=np.uint8).reshape(
            pm.height, pm.width, pm.n)
        img = arr[:, :, :3]
        try:
            txt = pg.get_text()[:400]
        except Exception:
            txt = ""
        img.flags.writeable = False
        out.append((img, txt))
    return out


def find_page(imgs, marker, last=True):
    """Номер страницы отчёта, заголовок которой содержит маркер."""
    hits = [i for i, (_, t) in enumerate(imgs) if marker in t]
    if not hits:
        return None
    return hits[-1] if last else hits[0]


FIG_ASPECT = A4[0] / A4[1]          # ширина/высота листа в дюймах


def count_intervals():
    """Число расчётных интервалов - чтобы найти нужную страницу отчёта."""
    try:
        from hydraulics_core import InputData
        from hydraulics_solver import make_intervals
        from hydraulics_core import find_input_file
        path = find_input_file(CFG.EXCEL_FILE)
        if not path:
            return None
        return len(make_intervals(InputData(path)))
    except Exception:
        return None


def section_index(imgs):
    """
    Номер наглядной страницы интервала. Текст из PDF извлекается не всегда,
    поэтому положение вычисляется по структуре отчёта: титул, конструкция,
    исходные данные, далее по две страницы на каждый интервал.
    """
    if not imgs:
        return 0
    i = find_page(imgs, "Секция")
    if i is None:
        n = count_intervals()
        i = 3 + 2 * (n - 1) if n else min(3, len(imgs) - 1)
    return min(max(i, 3), len(imgs) - 1)


def section_page(imgs):
    return imgs[section_index(imgs)][0] if imgs else None


def img_at(imgs, i):
    if not imgs:
        return None
    i = min(max(i, 0), len(imgs) - 1)
    return imgs[i][0]


def show_page(fig, img, rect, crop=None, frame=True):
    """
    Вставляет изображение страницы (или её части) в заданную область.
    Область подгоняется под пропорции картинки, чтобы она занимала место
    целиком, а не висела в середине с полями.
    """
    x0r, y0r, wr, hr = rect
    if img is None:
        ax = fig.add_axes(rect)
        ax.text(0.5, 0.5, "иллюстрация недоступна", ha="center",
                va="center", fontsize=9, color="#9A9A9C")
        ax.axis("off")
        return ax
    a = img
    if crop:
        h, w = a.shape[:2]
        cx0, cy0, cx1, cy1 = crop
        a = a[int(cy0 * h):int(cy1 * h), int(cx0 * w):int(cx1 * w)]

    # пропорции картинки в долях листа
    img_ar = a.shape[1] / a.shape[0]            # ширина/высота
    box_ar = (wr * FIG_ASPECT) / hr
    if img_ar > box_ar:                         # картинка шире области
        new_h = wr * FIG_ASPECT / img_ar
        rect = [x0r, y0r + (hr - new_h), wr, new_h]
    else:                                       # картинка выше области
        new_w = hr * img_ar / FIG_ASPECT
        rect = [x0r + (wr - new_w) / 2, y0r, new_w, hr]

    ax = fig.add_axes(rect)
    ax.imshow(a)
    ax.set_xticks([])
    ax.set_yticks([])
    for sp in ax.spines.values():
        sp.set_edgecolor(C["grid"] if frame else "none")
        sp.set_linewidth(0.8)
    return ax


