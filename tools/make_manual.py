def h2(fig, x, y, text, color=None):
    fig.add_artist(Line2D([x, x + 0.006], [y - 0.004, y + 0.014],
                          color=C["yellow"], lw=3.2, solid_capstyle="butt"))
    fig.text(x + 0.012, y, text, fontsize=11, fontweight="bold",
             color=color or C["text"])


def para(fig, x, y, text, width=100, size=9, color=None, lh=0.0195):
    for ln in textwrap.wrap(text, width):
        fig.text(x, y, ln, fontsize=size, color=color or "#3A3A3C")
        y -= lh
    return y


def bullets(fig, x, y, items, width=95, size=9, lh=0.0195, gap=0.006):
    for t in items:
        fig.text(x, y, "\u25cf", fontsize=5.5, color=C["accent2"],
                 va="baseline", zorder=5)
        first = True
        for ln in textwrap.wrap(t, width):
            fig.text(x + 0.014 if first else x + 0.014, y, ln, fontsize=size,
                     color="#3A3A3C")
            y -= lh
            first = False
        y -= gap
    return y


def note_box(fig, x, y, w, text, color=None, title=None):
    col = color or C["yellow"]
    lines = textwrap.wrap(text, 92)
    h = 0.020 * len(lines) + (0.024 if title else 0.010)
    fig.add_artist(FancyBboxPatch((x, y - h), w, h,
                                  boxstyle="round,pad=0.006",
                                  facecolor="#FBF7E8", edgecolor=col,
                                  lw=1.0, zorder=0,
                                  transform=fig.transFigure))
    yy = y - 0.020
    if title:
        fig.text(x + 0.014, yy, title, fontsize=9, fontweight="bold",
                 color=col if col != C["yellow"] else "#B08000")
        yy -= 0.021
    for ln in lines:
        fig.text(x + 0.014, yy, ln, fontsize=8.6, color="#3A3A3C")
        yy -= 0.020
    return y - h - 0.014


