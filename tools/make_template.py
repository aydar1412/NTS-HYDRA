def sheet(name, title, note, headers, widths, nrows=0,
          col1=None, example=None, comments=None, freeze=True,
          fill_from=1):
    name, title, note = T(name), T(title), T(note)
    headers = [T(h) for h in headers]
    col1 = [T(c) for c in col1] if col1 else col1
    comments = {T(k): T(v) for k, v in comments.items()} if comments else None
    example = [T(v) if isinstance(v, str) else v
               for v in example] if example else example
    """Создаёт лист единого оформления. fill_from - с какого столбца заливка."""
    ws = wb.create_sheet(name)
    ws["A1"] = title
    ws["A1"].font = TITLE
    ws["A2"] = note
    ws["A2"].font = NOTE
    ws.merge_cells(start_row=2, start_column=1, end_row=2,
                   end_column=max(len(headers), 5))
    ws.row_dimensions[2].height = 30

    ws.cell(row=3, column=1).fill = ACC_FILL
    for j in range(2, len(headers) + 1):
        ws.cell(row=3, column=j).fill = ACC_FILL
    ws.row_dimensions[3].height = 4

    for j, h in enumerate(headers, start=1):
        c = ws.cell(row=4, column=j, value=h)
        c.fill = HDR_FILL
        c.font = HDR_FONT
        c.alignment = Alignment(horizontal="center", vertical="center",
                                wrap_text=True)
        c.border = BOX
        if comments and h in comments:
            c.comment = Comment(comments[h], "NTS-HYDRA")
    ws.row_dimensions[4].height = 36

    for i in range(nrows):
        rr = 5 + i
        for j in range(1, len(headers) + 1):
            c = ws.cell(row=rr, column=j)
            c.border = BOX
            c.font = NORMAL
            c.alignment = Alignment(horizontal="center", vertical="center")
            if j >= fill_from + (1 if col1 else 0):
                c.fill = FILL_IN
        if col1 and i < len(col1):
            c = ws.cell(row=rr, column=1, value=col1[i])
            c.font = BOLD
            c.alignment = Alignment(horizontal="left", vertical="center")

    if example:
        rr = 5 + nrows + 1
        c = ws.cell(row=rr, column=1, value=T("ПРИМЕР →"))
        c.font = RED
        for j, v in enumerate(example, start=2):
            c = ws.cell(row=rr, column=j, value=v)
            c.font = EXAMPLE
            c.alignment = Alignment(horizontal="center")

    for j, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(j)].width = w
    if freeze:
        ws.freeze_panes = ws.cell(row=5, column=1)
    return ws


